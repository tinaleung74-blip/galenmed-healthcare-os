export function getLaboratoryAnalytesForTest(
  testCode: string
): LaboratoryAnalyteDefinition[] {
  return LABORATORY_ANALYTE_CATALOG.filter(
    (analyte) =>
      analyte.testCode === testCode
  ).map((analyte) => ({
    ...analyte,
    qualitativeOptions: [
      ...analyte.qualitativeOptions,
    ],
    normalQualitativeValues: [
      ...analyte.normalQualitativeValues,
    ],
  }))
}
